use std::path::{Path, PathBuf};
use std::process::{Command, Output};

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// Runs the CLI with no user config, so a real `~/.config/alias-deck/secrets.toml` never leaks in.
fn run(args: &[&str], shell_env: Option<&str>) -> Output {
    let empty = std::env::temp_dir().join(format!("alias-deck-cli-{}", std::process::id()));
    std::fs::create_dir_all(&empty).unwrap();
    let mut cmd = Command::new(env!("CARGO_BIN_EXE_alias-deck"));
    cmd.args(args).current_dir(root()).env("HOME", &empty).env("XDG_CONFIG_HOME", &empty).env_remove("SHELL");
    if let Some(s) = shell_env {
        cmd.env("SHELL", s);
    }
    cmd.output().unwrap()
}

fn text(b: &[u8]) -> String {
    String::from_utf8(b.to_vec()).unwrap()
}

#[test]
fn compiles_to_stdout_and_reports_omissions_on_stderr() {
    let out = run(&["compile", "examples/devkit.toml", "--shell", "pwsh", "--os", "macos"], None);
    assert!(out.status.success(), "{}", text(&out.stderr));
    let stdout = text(&out.stdout);
    assert!(stdout.starts_with("# Generated by alias-deck."), "source on stdout");
    assert!(stdout.contains("# target: pwsh on macos\n"));
    let stderr = text(&out.stderr);
    assert!(
        stderr.contains("alias-deck: devkit/git/groot: omitted: no body for pwsh (pack has: posix, fish)\n"),
        "{stderr}"
    );
    assert!(stderr.contains("alias-deck: devkit/toolchain/GITHUB_TOKEN: omitted: secret is not bound"), "{stderr}");
    assert!(stderr.contains("devkit/git/gs: note: pwsh rewrites"), "{stderr}");
    assert!(!stdout.contains("omitted"), "reports stay off stdout");
}

#[test]
fn secrets_file_binds_secrets() {
    let out = run(
        &["compile", "examples/devkit.toml", "--shell", "bash", "--os", "linux", "--secrets", "examples/secrets.toml"],
        None,
    );
    assert!(out.status.success());
    assert!(
        text(&out.stdout).contains("$(command secret-tool lookup service alias-deck account github-token 2>/dev/null)")
    );
    let stderr = text(&out.stderr);
    assert!(!stderr.contains("GITHUB_TOKEN") && stderr.contains("NPM_TOKEN: omitted"), "{stderr}");
}

#[test]
fn shell_defaults_to_the_login_shell() {
    let out = run(&["compile", "examples/devkit.toml", "--os", "linux"], Some("/usr/local/bin/fish"));
    assert!(out.status.success());
    assert!(text(&out.stdout).contains("# target: fish on linux\n"));
    let out = run(&["compile", "examples/devkit.toml"], None);
    assert_eq!(out.status.code(), Some(2), "no $SHELL and no --shell is a usage error");
    assert!(text(&out.stderr).contains("pass --shell"));
}

#[test]
fn parse_errors_point_at_file_line_and_column() {
    let dir = std::env::temp_dir().join(format!("alias-deck-cli-bad-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let bad = dir.join("bad.toml");
    std::fs::write(
        &bad,
        "format = 1\n[pack]\nname = \"p\"\nversion = \"1.0.0\"\nlicense = \"MIT\"\ndescription = \"d\"\n[groups.g.aliases]\nx = \"echo $HOME\"\n",
    )
    .unwrap();
    let out = run(&["compile", bad.to_str().unwrap(), "--shell", "zsh"], None);
    assert_eq!(out.status.code(), Some(1));
    assert!(out.stdout.is_empty(), "nothing is emitted for an invalid pack");
    let stderr = text(&out.stderr);
    assert!(stderr.contains("bad.toml:8:5: invalid value: the string form allows only plain words"), "{stderr}");
}

#[test]
fn later_packs_win() {
    let dir = std::env::temp_dir().join(format!("alias-deck-cli-mine-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let mine = dir.join("mine.toml");
    std::fs::write(
        &mine,
        "format = 1\n[pack]\nname = \"mine\"\nversion = \"1.0.0\"\nlicense = \"MIT\"\ndescription = \"d\"\n[groups.me.aliases]\ngs = \"git status\"\n",
    )
    .unwrap();
    let out =
        run(&["compile", "examples/devkit.toml", mine.to_str().unwrap(), "--shell", "zsh", "--os", "linux"], None);
    assert!(out.status.success());
    assert!(text(&out.stdout).contains("alias gs='git status'\n") && !text(&out.stdout).contains("git status -sb"));
    assert!(text(&out.stderr).contains("devkit/git/gs: omitted: shadowed by mine/me/gs"));
}

#[test]
fn help_exits_zero() {
    let out = run(&["compile", "--help"], None);
    assert!(out.status.success() && text(&out.stdout).starts_with("usage: alias-deck compile"));
}

#[test]
fn usage_errors() {
    for args in [&["compile"][..], &["compile", "x.toml", "--shell", "ksh"], &["compile", "x.toml", "--bogus"], &[]] {
        assert_eq!(run(args, None).status.code(), Some(2), "{args:?}");
    }
}
