//! One backend per shell family. Adding nushell means one `Shell` variant, one `Dialect`
//! variant, one `Quoting` variant, and one file here; the exhaustive matches fail the build
//! until all of them exist.

mod fish;
mod posix;
mod pwsh;

use crate::compile::{CompileOptions, Item, Note, Shell, Target};
use crate::model::{CommandName, Dialect, Os, PackMeta};
use crate::writer::{Quoting, Writer};

/// Facts about a shell, which `lower` consults, and rendering, which `compile` drives. A backend
/// prints only through `Writer`, and rendering cannot fail: every omission is decided earlier.
pub(crate) trait Backend {
    fn quoting(&self) -> Quoting;

    /// In-shell dialects this shell runs, most specific first.
    fn dialects(&self) -> &'static [Dialect];

    /// Names this shell refuses to define, or that would break its own syntax if redefined.
    fn is_reserved(&self, name: &CommandName) -> bool;

    /// Two names with one key are the same command in this shell.
    fn command_key(&self, name: &CommandName) -> String {
        name.as_str().to_owned()
    }

    fn list_separator(&self, _os: Os) -> char {
        ':'
    }

    fn notes(&self, _item: &Item<'_>) -> Vec<Note> {
        Vec::new()
    }

    fn header(&self, w: &mut Writer, target: Target, packs: &[&PackMeta]);

    fn render(&self, w: &mut Writer, item: &Item<'_>, options: &CompileOptions);
}

pub(crate) fn backend(shell: Shell) -> &'static dyn Backend {
    match shell {
        Shell::Bash => &posix::BASH,
        Shell::Zsh => &posix::ZSH,
        Shell::Fish => &fish::Fish,
        Shell::Pwsh => &pwsh::Pwsh,
    }
}

/// Only validated identifiers reach a comment, so no pack text can end the line and start code.
fn header_comments(w: &mut Writer, target: Target, packs: &[&PackMeta]) {
    w.code("# Generated by alias-deck. Do not edit; edit the pack and rebuild.\n");
    w.code("# target: ").code(target.shell.key()).code(" on ").code(target.os.key()).code("\n");
    for p in packs {
        w.code("# pack: ").name(&p.name).code(" ").name(&p.version).code("\n");
    }
}
