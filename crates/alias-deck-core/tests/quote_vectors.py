#!/usr/bin/env python3
"""Regenerate quote_vectors.tsv from an independent reference of the quoting rules.

usage: python3 quote_vectors.py

The input column is kept and extended with TARGETED. Every other column is recomputed here,
not by the Rust code, so `cargo test` pins the Rust quoters to this reference and
tests/shells.rs proves each row byte for byte in the real shells.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
TSV = os.path.join(HERE, "quote_vectors.tsv")

# Words that sit on a bare-set boundary in at least one shell.
TARGETED = [
    "%self", "%1", "100%", "a%b", "=ls", "a=b", "--color=auto", "a==ls", "--opt==ls", "a=x:=ls",
    "x:=y", "a:b", "-", "--", "-n", "--no-verify", "-Force", "-a_b", "_x", "007", "a,b", "@x",
    "x@y", "~", "~/x", "a.b", "./x", "-Dx.y", "it's", "it’s", "‘’‚‛",
    "", " ", "\t", "\n", "\r", "\\", "'", "''", "'''", "a'b'c",
]

SET = set("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_./:@%+,=-")
PWSH_BARE = re.compile(r"-{0,2}[A-Za-z][A-Za-z0-9_-]*\Z")


def posix(s):
    # zsh EQUALS expands a leading `=cmd`; MAGIC_EQUAL_SUBST also expands `==cmd` and `:=cmd`.
    if s and set(s) <= SET and not s.startswith("=") and "==" not in s and ":=" not in s:
        return s
    return "'" + s.replace("'", "'\\''") + "'"


def fish(s):
    # fish 4.9 still expands the word `%self` to its PID.
    if s and set(s) <= SET and not s.startswith("%"):
        return s
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def pwsh_expr(s):
    return "'" + "".join(c * 2 if c in "'‘’‚‛" else c for c in s) + "'"


def pwsh_arg(s):
    return s if PWSH_BARE.match(s) else pwsh_expr(s)


def main():
    inputs = []
    with open(TSV, encoding="utf-8") as f:
        for line in f:
            if not line.startswith("#"):
                inputs.append(bytes.fromhex(line.rstrip("\n").split("\t")[0]).decode())
    seen, rows = set(), []
    for s in inputs + TARGETED:
        if s not in seen:
            seen.add(s)
            rows.append(s)
    hx = lambda s: s.encode().hex()
    with open(TSV, "w", encoding="utf-8") as f:
        f.write("# input\tposix\tfish\tpwsh_arg\tpwsh_expr (hex UTF-8). Generated by quote_vectors.py.\n")
        for s in rows:
            f.write("\t".join(hx(c) for c in (s, posix(s), fish(s), pwsh_arg(s), pwsh_expr(s))) + "\n")
    print(f"{len(rows)} vectors")


if __name__ == "__main__":
    main()
